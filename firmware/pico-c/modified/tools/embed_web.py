#!/usr/bin/env python3
"""Build installed gzip browser files and small firmware descriptors, entirely offline."""
import argparse
import base64
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = [('index.html', 'text/html; charset=utf-8'),
          ('app.js', 'application/javascript; charset=utf-8'),
          ('api-explorer.js', 'application/javascript; charset=utf-8'),
          ('history.js', 'application/javascript; charset=utf-8'),
          ('style.css', 'text/css; charset=utf-8')]
DEVICE_NAMES = {'index.html': 'i.gz', 'app.js': 'a.gz', 'api-explorer.js': 'e.gz',
                'style.css': 's.gz', 'history.js': 'h.gz'}


def generate():
    parts = ['/* Generated by tools/embed_web.py from web/. Do not edit. */',
             '#include "pico_c/web_assets.h"', '']
    sizes = []
    outputs = {}
    manifest = {'schema_version': 1, 'block_size': 4096, 'metadata_per_file': 512,
                'fail_safe': False, 'assets': []}
    for name, content_type in ASSETS:
        raw = (ROOT / 'web' / name).read_bytes()
        if name == 'index.html':
            # The deployed recovery protocol has five fixed website files.
            icon_link = b'href="/favicon.ico"'
            if raw.count(icon_link) != 1:
                raise ValueError('Expected one local favicon link in the website index')
            icon = base64.b64encode((ROOT / 'web/favicon.ico').read_bytes())
            raw = raw.replace(icon_link, b'href="data:image/x-icon;base64,' + icon + b'"')
            # The installed site uses five fixed slots. Bundle the extra modules
            # into the script slot with space and omit their standalone tags.
            for module in ('controls.js', 'recipes.js'):
                tag = f'  <script src="/{module}" defer></script>\n'.encode()
                if raw.count(tag) != 1:
                    raise ValueError(f'Expected one script tag for {module}')
                raw = raw.replace(tag, b'')
        elif name == 'history.js':
            for module in ('controls.js', 'recipes.js'):
                raw += b'\n' + (ROOT / 'web' / module).read_bytes()
        packed = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
        # gzip.compress varies the OS header byte across supported Python versions.
        packed[9] = 255
        payload = name + '.gz'
        # Below 64 KiB the pinned SimpleLink allocator rounds creation maxima
        # to 256-byte units; each file adds 512 metadata bytes before the 4 KiB
        # block rounding. These maxima use the whole final block without
        # accidentally allocating another block just for metadata.
        # The installed recovery's pico_recovery_file_limit uses these fixed
        # per-file maxima, even if the aggregate serial flash has free space.
        limit = 3584 if name in ('style.css', 'api-explorer.js') else 7680
        if len(packed) > limit:
            raise ValueError(f'{name}: {len(packed)} gzip bytes exceed the recovery limit of {limit}')
        blocks = (len(packed) + 512 + 4095) // 4096
        entry = {'source': name, 'file_path': '/local/web/' + DEVICE_NAMES[name],
                 'payload': payload, 'content_type': content_type,
                 'content_encoding': 'gzip', 'length': len(packed),
                 'max_size': blocks * 4096 - 512, 'allocation_blocks': blocks,
                 'sha256': hashlib.sha256(packed).hexdigest(),
                 'source_length': len(raw), 'source_sha256': hashlib.sha256(raw).hexdigest()}
        manifest['assets'].append(entry)
        outputs[ROOT / 'firmware/web' / payload] = bytes(packed)
        sizes.append((name, len(raw), len(packed)))
    parts.append('const PicoHttpAsset pico_web_assets[] = {')
    for entry in manifest['assets']:
        names = ['/' + entry['source']]
        if entry['source'] == 'index.html':
            names.insert(0, '/')
        parts.append('    /* gzip SHA-256: ' + entry['sha256'] + ' */')
        for path in names:
            parts.append('    {"' + path + '", "' + entry['content_type'] + '", "gzip", NULL, '
                         + str(entry['length']) + ', "' + entry['file_path'] + '"},')
    parts.extend(['};', 'const size_t pico_web_assets_count = sizeof(pico_web_assets) / sizeof(pico_web_assets[0]);', ''])
    outputs[ROOT / 'src/local_web_assets.c'] = '\n'.join(parts).encode()
    outputs[ROOT / 'firmware/web/manifest.json'] = (json.dumps(manifest, indent=2) + '\n').encode()
    return outputs, sizes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if descriptors, manifest, or gzip files are stale')
    args = parser.parse_args()
    outputs, sizes = generate()
    stale = [path for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
    if args.check and stale:
        parser.error('Generated web assets are stale; run tools/embed_web.py: ' +
                     ', '.join(str(path.relative_to(ROOT)) for path in stale))
    if not args.check:
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(outputs[path])
    for name, raw, packed in sizes:
        print(f'{name}: {raw} bytes -> {packed} gzip bytes')
    print('Total installed flash payload:', sum(size for _, _, size in sizes), 'bytes (not embedded in firmware)')
    blocks = sum((size + 512 + 4095) // 4096 for _, _, size in sizes)
    print(f'SimpleLink allocation: {blocks} blocks / {blocks * 4096} bytes, including metadata; fail-safe off')


if __name__ == '__main__':
    main()
